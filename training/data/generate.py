#!/usr/bin/env python3
"""Deterministic, seedable synthetic episode generator (training/CONTRACT.md).

    python3 training/data/generate.py --out training/data/out --prefix sample_ \
        --train 2000 --val 200 --test 200 --seed 7 --holdout-family slot_conflict

Same arguments, same bytes: every episode's randomness comes from
random.Random(f"{base_seed}:{scenario}:{seed}") (string seeds are hashed with
SHA-512, so this is stable across runs and machines). No network, no API keys.

Splits are disjoint by (scenario, seed): train seeds start at 0, val at
1_000_000, test at 2_000_000. One scenario family is held out of train and val
entirely and appears only in test (default `slot_conflict`).

Library use:
    from generate import build_episode, generate_split
    ep = build_episode("book_after_availability_busy", seed=123)
"""

from __future__ import annotations

import argparse
import json
import os
import random
import sys
from collections import Counter, defaultdict
from typing import Any, Dict, Iterable, List, Optional, Sequence

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import elle_time as T  # noqa: E402
from episode import Ep  # noqa: E402
from scenarios import BY_NAME, FAMILIES, SCENARIOS, RetryScenario, Scenario  # noqa: E402

SPLIT_SEED_BASE = {"train": 0, "val": 1_000_000, "test": 2_000_000}
DEFAULT_HOLDOUT = "slot_conflict"
MAX_RETRIES = 20


def build_episode(scenario: str, seed: int, split: str = "train", ep_id: str = "ep_000000",
                  base_seed: int = 0, lang: Optional[str] = None) -> Dict[str, Any]:
    """Build one episode. Deterministic in (scenario, seed, base_seed, lang)."""
    sc = BY_NAME[scenario]
    last: Optional[Exception] = None
    for attempt in range(MAX_RETRIES):
        key = f"{base_seed}:{scenario}:{seed}" + (f":retry{attempt}" if attempt else "")
        rng = random.Random(key)
        ep_lang = lang
        if ep_lang is None:
            ep_lang = "es" if ("es" in sc.langs and rng.random() < sc.es_share) else "en"
        if ep_lang not in sc.langs:
            raise ValueError(f"{scenario} does not support lang {ep_lang}")
        now = T.random_now(rng)
        ep = Ep(scenario, sc.family, seed, rng, now, ep_lang)
        try:
            sc.fn(ep)
        except RetryScenario as e:
            last = e
            continue
        return ep.finish(ep_id, split)
    raise RuntimeError(f"{scenario}/{seed}: gave up after {MAX_RETRIES} retries ({last!r})")


def _weighted(rng: random.Random, pool: Sequence[Scenario]) -> Scenario:
    return rng.choices(list(pool), weights=[s.weight for s in pool], k=1)[0]


def generate_split(split: str, n: int, base_seed: int = 0, holdout_family: Optional[str] = DEFAULT_HOLDOUT,
                   holdout_share: float = 0.3, start_index: int = 1) -> List[Dict[str, Any]]:
    """`n` episodes for one split. Train/val never contain the held-out family;
    test gets `holdout_share` of its episodes from it."""
    rng = random.Random(f"{base_seed}:{split}:schedule")
    in_dist = [s for s in SCENARIOS if s.family != holdout_family]
    held = [s for s in SCENARIOS if s.family == holdout_family]
    out = []
    per_scenario_seed: Counter = Counter()
    for i in range(n):
        if split == "test" and held and rng.random() < holdout_share:
            sc = _weighted(rng, held)
        else:
            sc = _weighted(rng, in_dist)
        seed = SPLIT_SEED_BASE[split] + per_scenario_seed[sc.name]
        per_scenario_seed[sc.name] += 1
        ep = build_episode(sc.name, seed, split, f"ep_{start_index + i:06d}", base_seed)
        if sc.family == holdout_family:
            ep["labels"]["held_out_family"] = True
        out.append(ep)
    return out


def write_jsonl(path: str, episodes: Iterable[Dict[str, Any]]) -> None:
    with open(path, "w", encoding="utf-8") as f:
        for ep in episodes:
            f.write(json.dumps(ep, ensure_ascii=False, separators=(",", ":")) + "\n")


def read_jsonl(path: str) -> List[Dict[str, Any]]:
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


# --- stats ----------------------------------------------------------------------------

def _pct(a: int, b: int) -> str:
    return f"{100 * a / b:.1f}%" if b else "-"


def _quantiles(xs: List[float]) -> str:
    if not xs:
        return "-"
    xs = sorted(xs)

    def q(p: float) -> float:
        return xs[min(len(xs) - 1, int(p * (len(xs) - 1) + 0.5))]
    return f"{q(0):.2f} / {q(0.25):.2f} / {q(0.5):.2f} / {q(0.75):.2f} / {q(0.95):.2f} / {q(1):.2f}"


def stats_markdown(splits: Dict[str, List[Dict[str, Any]]], args_line: str, holdout: Optional[str]) -> str:
    lines = ["# Sample dataset statistics", "",
             f"Generated by `{args_line}`.", "",
             "Synthetic text-and-timing episodes (no audio). See README.md for what they are and are not.", ""]
    allep = [e for eps in splits.values() for e in eps]
    lines += ["## Totals", "", "| split | episodes | negatives | Spanish (any) | held-out family | events/ep (mean) | duration s (mean) |",
              "|---|---|---|---|---|---|---|"]
    for name, eps in splits.items():
        neg = sum(e["labels"]["negative"] for e in eps)
        es = sum(e["labels"]["lang"] != "en" for e in eps)
        ho = sum(bool(e["labels"].get("held_out_family")) for e in eps)
        nev = sum(len(e["events"]) for e in eps) / max(1, len(eps))
        durs = [max((ev["t"] + ev.get("dur", 0)) for ev in e["events"]) for e in eps]
        lines.append(f"| {name} | {len(eps)} | {neg} ({_pct(neg, len(eps))}) | {es} ({_pct(es, len(eps))}) | "
                     f"{ho} | {nev:.1f} | {sum(durs) / max(1, len(durs)):.1f} |")
    lines += ["", f"Held-out family: `{holdout}` (test only)." if holdout else "No held-out family.", ""]

    lines += ["## Episodes per scenario", "", "| scenario | family | train | val | test |", "|---|---|---|---|---|"]
    fam = {s.name: s.family for s in SCENARIOS}
    for s in SCENARIOS:
        row = [str(sum(e["scenario"] == s.name for e in splits.get(k, []))) for k in ("train", "val", "test")]
        lines.append(f"| {s.name} | {fam[s.name]} | " + " | ".join(row) + " |")
    lines += ["", f"{len(SCENARIOS)} scenarios in {len(FAMILIES)} families.", ""]

    lines += ["## Read / write mix (episode kind)", "", "| kind | episodes | share |", "|---|---|---|"]
    kinds = Counter(e["labels"]["kind"] for e in allep)
    for k in ("read", "write", "mixed", "none"):
        lines.append(f"| {k} | {kinds[k]} | {_pct(kinds[k], len(allep))} |")
    calls = Counter(ev["name"] for e in allep for ev in e["events"] if ev["type"] == "tool_call")
    lines += ["", "| tool | calls |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(calls.items())]

    lines += ["", "## Tool latency (seconds)", "", "min / p25 / median / p75 / p95 / max", "",
              "| tool | n | quantiles | share > 0.7 s |", "|---|---|---|---|"]
    lat: Dict[str, List[float]] = defaultdict(list)
    for e in allep:
        names = {ev["id"]: ev["name"] for ev in e["events"] if ev["type"] == "tool_call"}
        for ev in e["events"]:
            if ev["type"] == "tool_result":
                lat[names[ev["id"]]].append(ev["latency_s"])
    for k in sorted(lat):
        xs = lat[k]
        lines.append(f"| {k} | {len(xs)} | {_quantiles(xs)} | {_pct(sum(x > 0.7 for x in xs), len(xs))} |")
    hist = Counter()
    edges = [0.25, 0.5, 0.7, 1.0, 1.5, 2.0, 3.0, 4.0, 6.5]
    for k in ("check_availability", "get_my_bookings"):
        for x in lat.get(k, []):
            hist[next(b for b in edges if x <= b)] += 1
    lines += ["", "Read latency histogram (upper bucket edge, s):", "", "| <= s | reads |", "|---|---|"]
    lines += [f"| {b} | {hist[b]} |" for b in edges]

    lines += ["", "## Overlap and interruptions", ""]
    barge = sum(1 for e in allep for ev in e["events"] if ev.get("interrupted"))
    bc = sum(1 for e in allep for ev in e["events"] if ev.get("act") == "backchannel")
    ov = 0
    for e in allep:
        sp = [ev for ev in e["events"] if ev["type"] == "speech"]
        for a in sp:
            if a["ch"] != "caller":
                continue
            if any(b["ch"] == "elle" and a["t"] < b["t"] + b["dur"] and b["t"] < a["t"] + a["dur"] for b in sp):
                ov += 1
                break
    lines += [f"- Episodes with at least one cross-channel overlap: {ov} ({_pct(ov, len(allep))})",
              f"- Elle utterances cut off by a barge-in: {barge}",
              f"- Backchannels: {bc}", ""]
    neg = Counter(e["labels"].get("negative_kind") for e in allep if e["labels"]["negative"])
    lines += ["## Negatives", "", "| negative_kind | episodes |", "|---|---|"] + \
        [f"| {k} | {v} |" for k, v in sorted(neg.items())] + [""]
    return "\n".join(lines)


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "out"))
    ap.add_argument("--prefix", default="sample_")
    ap.add_argument("--train", type=int, default=2000)
    ap.add_argument("--val", type=int, default=200)
    ap.add_argument("--test", type=int, default=200)
    ap.add_argument("--seed", type=int, default=7, help="base seed")
    ap.add_argument("--holdout-family", default=DEFAULT_HOLDOUT,
                    help=f"family kept out of train/val (one of {', '.join(FAMILIES)}; 'none' to disable)")
    ap.add_argument("--holdout-share", type=float, default=0.3)
    ap.add_argument("--no-stats", action="store_true")
    a = ap.parse_args(argv)
    holdout = None if a.holdout_family in ("", "none") else a.holdout_family
    if holdout and holdout not in FAMILIES:
        ap.error(f"unknown family {holdout}")
    os.makedirs(a.out, exist_ok=True)
    splits: Dict[str, List[Dict[str, Any]]] = {}
    idx = 1
    for split, n in (("train", a.train), ("val", a.val), ("test", a.test)):
        splits[split] = generate_split(split, n, a.seed, holdout, a.holdout_share, start_index=idx)
        idx += n
        path = os.path.join(a.out, f"{a.prefix}{split}.jsonl")
        write_jsonl(path, splits[split])
        print(f"wrote {len(splits[split])} episodes to {path}")
    if not a.no_stats:
        args_line = (f"python3 training/data/generate.py --prefix {a.prefix} --train {a.train} --val {a.val} "
                     f"--test {a.test} --seed {a.seed} --holdout-family {a.holdout_family}")
        with open(os.path.join(a.out, "STATS.md"), "w", encoding="utf-8") as f:
            f.write(stats_markdown(splits, args_line, holdout))
        print(f"wrote {os.path.join(a.out, 'STATS.md')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
